#!/usr/bin/env node
// measure.cjs: keystrokes to reach every widget on the user's bar, per edge
// and scheme, with and without zone jumps, and by name (measurements.json).
const fs = require('fs'), vm = require('vm');
const ctx = { window: {} }; vm.createContext(ctx);
vm.runInContext(fs.readFileSync(__dirname + '/layout.js', 'utf8'), ctx);
const Nav = require('./nav.js'), bar = ctx.window.BAR;
const arrows = ['ArrowLeft', 'ArrowRight', 'ArrowUp', 'ArrowDown', 'Enter'];
const out = {};
function stats(list) {
  const k = list.map(x => x.keys).filter(Number.isFinite).sort((a, b) => a - b);
  return { median: k[Math.floor(k.length / 2)], max: k[k.length - 1], mean: +(k.reduce((a, b) => a + b, 0) / k.length).toFixed(1),
    unreachable: list.filter(x => !Number.isFinite(x.keys)).map(x => x.name), over6: list.filter(x => x.keys > 6).length, count: list.length };
}
for (const position of ['right', 'top']) for (const scheme of ['along', 'updown']) {
  const a = Nav.reach(bar, position, scheme, arrows), t = Nav.reach(bar, position, scheme, arrows.concat(['Tab', 'Shift+Tab', 'Home', 'End']));
  out[position + '/' + scheme] = { arrows: stats(a), withTab: stats(t), groupKeys: Nav.keymap(position, scheme).clash.length ? 'clash: ' + Nav.keymap(position, scheme).clash.join(' ') : 'ok',
    worst: t.filter(x => Number.isFinite(x.keys)).sort((x, y) => y.keys - x.keys).slice(0, 4).map(x => x.name + ' ' + x.keys) };
}
const f = Nav.findCost(bar);
out.find = stats(f);
out.findTyped = f.map(x => x.name + ' → /' + x.typed + (x.rank ? ' +' + x.rank + '↓' : ''));
fs.writeFileSync(__dirname + '/measurements.json', JSON.stringify(out, null, 1));
console.log(JSON.stringify(out, null, 1).slice(0, 4000));
fs.writeFileSync(__dirname + '/measurements.js', '// Generated by measure.cjs.\nwindow.MEASURE = ' + JSON.stringify(out) + ';\n');
