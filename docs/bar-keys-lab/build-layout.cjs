#!/usr/bin/env node
// build-layout.cjs [hyprctl-binds.txt]: the user's bar for the lab, in bar
// order (layout.js): widgets on the bar, on-demand widgets behind their
// zone's dots, groups with their members, each with its name, capture and
// direct shortcut. Reads shell.json, widgets.json, plugin manifests and
// Hyprland's binding files; writes nothing outside this folder.
const fs = require('fs'), vm = require('vm'), path = require('path'), os = require('os');
const here = __dirname, home = os.homedir();
const S = vm.createContext({});
vm.runInContext(fs.readFileSync(path.join(here, '../../ShortcutModel.js'), 'utf8'), S);
const bar = JSON.parse(fs.readFileSync(path.join(home, '.config/omarchy/shell.json'), 'utf8')).bar;
const caps = JSON.parse(fs.readFileSync(path.join(here, 'widgets.json'), 'utf8')).widgets;
const byInstance = {};
for (const [key, w] of Object.entries(caps)) byInstance[w.instance] = key;

const names = {};
const manifests = ['/usr/share/omarchy/shell/plugins'];
function walk(dir) {
  for (const f of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, f.name);
    if (f.isDirectory()) walk(p);
    else if (/manifest\.json$/.test(f.name)) try { const m = JSON.parse(fs.readFileSync(p, 'utf8')); if (m.id && m.name) names[m.id] = m.name } catch (e) {}
  }
}
manifests.forEach(walk);
const pluginDir = path.join(home, '.config/omarchy/plugins');
for (const id of fs.readdirSync(pluginDir)) try { const m = JSON.parse(fs.readFileSync(path.join(pluginDir, id, 'manifest.json'), 'utf8')); names[id] = m.name || id } catch (e) {}

const files = [];
const omarchyDir = '/usr/share/omarchy/default/hypr/bindings';
for (const f of fs.readdirSync(omarchyDir)) files.push({ origin: 'omarchy', text: fs.readFileSync(path.join(omarchyDir, f), 'utf8') });
const hyprDir = path.join(home, '.config/hypr');
for (const f of fs.readdirSync(hyprDir)) if (/\.lua$/.test(f) && f !== 'powerbar.lua') files.push({ origin: 'config', text: fs.readFileSync(path.join(hyprDir, f), 'utf8') });
const defaults = S.readDefaults(files);
const binds = process.argv[2] ? S.parseBinds(fs.readFileSync(process.argv[2], 'utf8')) : [];
const config = bar.powerbarShortcuts || {};

const groups = bar.powerbarGroups || [];
const memberOf = {};
for (const g of groups) for (const k of g.items) memberOf[k] = g;
function widget(e) {
  const key = byInstance[e.powerbarInstance];
  const s = S.effective('widget:' + e.id, config, defaults, binds);
  return { kind: 'widget', id: e.id, instance: e.powerbarInstance, key: key || null, name: names[e.id] || e.id.split('.').pop(),
    shortcut: s.keys, mode: e.powerbarVisibility || 'shown' };
}
const zones = {};
for (const zone of ['left', 'center', 'right']) {
  const out = [];
  const entries = bar.layout[zone].filter(e => e.powerbarVisibility !== 'hidden');
  const placeGroups = before => groups.filter(g => g.section === zone && g.visibility !== 'hidden' && g.before === before)
    .forEach(g => out.push({ kind: 'group', id: g.id, name: g.label, key: 'group-' + g.label.toLowerCase(),
      members: g.items.map(k => bar.layout[zone].concat(bar.layout.left, bar.layout.center, bar.layout.right).find(e => e.powerbarInstance === k)).filter(Boolean).map(widget),
      shortcut: S.effective('group:' + g.id, config, defaults, binds).keys }));
  for (const e of entries) {
    placeGroups(e.powerbarInstance);
    if (memberOf[e.powerbarInstance]) continue;
    out.push(widget(e));
  }
  placeGroups('');
  zones[zone] = out;
}
// Place-based shortcuts: the Nth panel in the right zone (approximate: every
// shown widget there that Omarchy opens counts).
const lab = { zones, anchor: bar.centerAnchor || 'omarchy.clock', position: bar.position, onDemand: bar.powerbarOnDemand || 'inline' };
fs.writeFileSync(path.join(here, 'layout.js'), '// Generated by build-layout.cjs from the user\'s shell.json.\nwindow.BAR = ' + JSON.stringify(lab) + ';\n');
const count = Object.values(zones).flat().reduce((n, i) => n + 1 + (i.members ? i.members.length : 0), 0);
console.log('items', count, Object.fromEntries(Object.entries(zones).map(([z, l]) => [z, l.map(i => i.name + (i.mode === 'managed' ? '*' : '') + (i.shortcut ? '[' + S.label(i.shortcut) + ']' : '') + (i.members ? '{' + i.members.map(m => m.name).join(',') + '}' : '')).join(' | ')])));
