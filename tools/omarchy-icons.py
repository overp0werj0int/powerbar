#!/usr/bin/env python3
# omarchy-icons.py [bar font file] > OmarchyIcons.js
#
# The icon picker's Omarchy sources, read from this machine:
#   logos   every glyph in Omarchy's own font (its logo and AI tool logos)
#   glyphs  every Nerd Font glyph Omarchy's shell, menus, configs and scripts
#           use, named from the bar font's own glyph names (md-folder, fa-...)
#           and ordered by how often Omarchy uses it
# Standard library only. Run it again after an Omarchy update.
import json, os, re, struct, subprocess, sys
  # the 258 Macintosh names are never Nerd Font icon names; indexes < 258 are skipped
def tables(b):
    n = struct.unpack(">H", b[4:6])[0]
    return {b[12+16*i:16+16*i].decode("latin1"): struct.unpack(">II", b[20+16*i:28+16*i]) for i in range(n)}
def cmap(b, off):
    n = struct.unpack(">H", b[off+2:off+4])[0]
    best = None
    for i in range(n):
        pid, eid, o = struct.unpack(">HHI", b[off+4+8*i:off+12+8*i])
        fmt = struct.unpack(">H", b[off+o:off+o+2])[0]
        if fmt == 12: best = (12, off+o); break
        if fmt == 4 and pid in (0, 3): best = best or (4, off+o)
    fmt, o = best; out = {}
    if fmt == 12:
        groups = struct.unpack(">I", b[o+12:o+16])[0]
        for g in range(groups):
            s, e, gid = struct.unpack(">III", b[o+16+12*g:o+28+12*g])
            for c in range(s, e+1): out[c] = gid + c - s
    else:
        seg = struct.unpack(">H", b[o+6:o+8])[0] // 2
        ends = struct.unpack(">%dH" % seg, b[o+14:o+14+2*seg]); p = o+16+2*seg
        starts = struct.unpack(">%dH" % seg, b[p:p+2*seg]); p += 2*seg
        deltas = struct.unpack(">%dh" % seg, b[p:p+2*seg]); p += 2*seg
        ro = p
        for i in range(seg):
            r = struct.unpack(">H", b[ro+2*i:ro+2*i+2])[0]
            for c in range(starts[i], ends[i]+1):
                if c == 0xFFFF: continue
                if r == 0: gid = (c + deltas[i]) & 0xFFFF
                else:
                    a = ro + 2*i + r + 2*(c - starts[i]); gid = struct.unpack(">H", b[a:a+2])[0]
                    if gid: gid = (gid + deltas[i]) & 0xFFFF
                if gid: out[c] = gid
    return out
def post(b, off):
    if struct.unpack(">I", b[off:off+4])[0] != 0x00020000: return {}
    n = struct.unpack(">H", b[off+32:off+34])[0]
    idx = struct.unpack(">%dH" % n, b[off+34:off+34+2*n]); p = off+34+2*n; names = []
    count = max([i-258 for i in idx if i >= 258] + [-1]) + 1
    while len(names) < count:
        l = b[p]; names.append(b[p+1:p+1+l].decode("latin1")); p += 1+l
    return {g: names[i-258] for g, i in enumerate(idx) if i >= 258}

def font_names(path):
    b = open(path, "rb").read(); t = tables(b)
    cm = cmap(b, t["cmap"][0]); names = post(b, t["post"][0])
    return cm, names

root = os.environ.get("OMARCHY_PATH", "/usr/share/omarchy")
bar_font = sys.argv[1] if len(sys.argv) > 1 else subprocess.run(
    ["fc-match", "-f", "%{file}", "JetBrainsMono Nerd Font"], capture_output=True, text=True).stdout.strip()
cm, gnames = font_names(bar_font)
nerd = {c: gnames[g] for c, g in cm.items() if (0xE000 <= c <= 0xF8FF or c >= 0xF0000) and g in gnames}

# Omarchy's font: names from its post table; a glyph with a standard name
# (pi) has none there, so it keeps a fixed one.
STANDARD = {0xE901: "pi"}
ocm, onames = font_names("/usr/share/fonts/omarchy/omarchy.ttf")
AI = {"pi", "opencode", "omp", "grok", "codex", "lmstudio", "ollama", "t3code", "hermes", "perplexity", "openclaw", "cursor"}
logos = []
for c in sorted(ocm):
    if c < 0xE000: continue
    name = onames.get(ocm[c]) or STANDARD.get(c) or "omarchy %04x" % c
    logos.append([c, name, ["ai"] if name in AI else []])

use = {}
pair = re.compile(r"\\u(d[89ab][0-9a-f]{2})\\u(d[c-f][0-9a-f]{2})", re.I)
single = re.compile(r"\\u([ef][0-9a-f]{3})", re.I)
for sub in ("shell", "bin", "default", "config"):
    for d, _, files in os.walk(os.path.join(root, sub)):
        for f in files:
            try: s = open(os.path.join(d, f), encoding="utf-8").read()
            except Exception: continue
            s = pair.sub(lambda m: chr(0x10000 + ((int(m[1], 16) - 0xD800) << 10) + (int(m[2], 16) - 0xDC00)), s)
            s = single.sub(lambda m: chr(int(m[1], 16)), s)
            for ch in set(s):
                c = ord(ch)
                if c in nerd: use[c] = use.get(c, 0) + s.count(ch)
glyphs = [[c, nerd[c], n] for c, n in sorted(use.items(), key=lambda x: (-x[1], nerd[x[0]]))]

print("// Generated by tools/omarchy-icons.py from " + root + " and " + os.path.basename(bar_font) + ". Do not edit.")
print("// logos: [code point, name, tags] in Omarchy's font; glyphs: [code point, Nerd Font name, uses].")
print("var logos = " + json.dumps(logos, separators=(",", ":")))
print("var glyphs = " + json.dumps(glyphs, separators=(",", ":")))
print("if (typeof module !== \"undefined\") module.exports = { logos: logos, glyphs: glyphs }")
